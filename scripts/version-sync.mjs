// Writes android/version.properties from package.json.
// versionCode = MAJOR*10000 + MINOR*100 + PATCH (1.0.0 → 10000), so every release increases it.
import fs from 'node:fs';
const pkg = JSON.parse(fs.readFileSync(new URL('../package.json', import.meta.url), 'utf8'));
const m = /^(\d+)\.(\d+)\.(\d+)$/.exec(pkg.version);
if (!m) { console.error(`package.json version "${pkg.version}" must be MAJOR.MINOR.PATCH`); process.exit(1); }
const [maj, min, pat] = m.slice(1).map(Number);
if (min > 99 || pat > 99) { console.error('MINOR and PATCH must be ≤ 99 for the versionCode scheme'); process.exit(1); }
const code = maj * 10000 + min * 100 + pat;
fs.writeFileSync(new URL('../android/version.properties', import.meta.url),
  `# Generated by \`npm run version:sync\` from package.json. Do not edit by hand.\nVERSION_NAME=${pkg.version}\nVERSION_CODE=${code}\n`);
console.log(`android/version.properties → ${pkg.version} (${code})`);
