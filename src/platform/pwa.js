/* PWA support for the web build: offline Service Worker, update prompt, install prompt.
   - The worker (dist/sw.js, generated by scripts/generate-pwa.mjs) caches only static files.
     Financial data stays in this browser's localStorage and is never put in CacheStorage.
   - A new version waits until the user chooses to update; pending edits are saved first. */

const isStandalone = () => {
  try {
    return window.matchMedia('(display-mode: standalone)').matches || window.navigator.standalone === true;
  } catch (e) { return false; }
};

function panel(id, text, actions) {
  if (document.getElementById(id)) return null;
  const el = document.createElement('aside');
  el.id = id;
  el.className = 'wg-pwa-panel';
  el.setAttribute('role', 'status');
  const msg = document.createElement('span');
  msg.textContent = text;
  el.append(msg);
  const row = document.createElement('div');
  row.className = 'wg-pwa-acts';
  for (const a of actions) {
    const b = document.createElement('button');
    b.type = 'button';
    b.textContent = a.label;
    b.className = a.primary ? 'wg-pwa-btn pri' : 'wg-pwa-btn';
    b.addEventListener('click', () => a.run(b, el));
    row.append(b);
  }
  el.append(row);
  document.body.append(el);
  return el;
}

function offerUpdate(registration) {
  if (!registration.waiting || !navigator.serviceWorker.controller) return;
  panel('wg-pwa-update', '財富花園有新版本。請先完成正在輸入的內容，再選擇更新。', [
    {
      label: '立即更新', primary: true,
      run: (btn) => {
        btn.disabled = true;
        btn.textContent = '更新中…';
        // Ask the app to write any pending edit to localStorage before the page reloads.
        try { window.dispatchEvent(new Event('wealthgarden:flush')); } catch (e) { /* ignore */ }
        let done = false;
        navigator.serviceWorker.addEventListener('controllerchange', () => {
          if (done) return;
          done = true;
          window.location.reload();
        }, { once: true });
        if (registration.waiting) registration.waiting.postMessage({ type: 'SKIP_WAITING' });
      }
    },
    { label: '稍後', run: (btn, el) => el.remove() }
  ]);
}

export async function registerPWA() {
  if (!('serviceWorker' in navigator)) return;
  const local = location.hostname === 'localhost' || location.hostname === '127.0.0.1';
  if (location.protocol !== 'https:' && !local) return;
  try {
    const registration = await navigator.serviceWorker.register('./sw.js', { scope: './', updateViaCache: 'none' });
    if (registration.waiting) offerUpdate(registration);
    registration.addEventListener('updatefound', () => {
      const worker = registration.installing;
      if (!worker) return;
      worker.addEventListener('statechange', () => { if (worker.state === 'installed') offerUpdate(registration); });
    });
    const check = () => { if (navigator.onLine) registration.update().catch(() => {}); };
    window.addEventListener('online', check);
    document.addEventListener('visibilitychange', () => { if (document.visibilityState === 'visible') check(); });
  } catch (err) {
    // Offline support failing must never block access to the data.
    console.warn('財富花園 PWA 離線快取無法啟用：', err);
  }
}

const DISMISS_KEY = 'wg-install-dismissed';

/* Android / desktop Chrome & Edge fire beforeinstallprompt; show a small, dismissible offer. */
export function setupInstallPrompt() {
  if (isStandalone()) return;
  let dismissed = false;
  try { dismissed = window.localStorage.getItem(DISMISS_KEY) === '1'; } catch (e) { /* ignore */ }
  window.addEventListener('beforeinstallprompt', (evt) => {
    evt.preventDefault();
    if (dismissed) return;
    panel('wg-pwa-install', '可以把財富花園安裝到主畫面，像 App 一樣開啟，離線也能使用。', [
      {
        label: '安裝', primary: true,
        run: async (btn, el) => {
          el.remove();
          try { await evt.prompt(); await evt.userChoice; } catch (e) { /* ignore */ }
        }
      },
      {
        label: '不用了',
        run: (btn, el) => {
          el.remove();
          dismissed = true;
          try { window.localStorage.setItem(DISMISS_KEY, '1'); } catch (e) { /* ignore */ }
        }
      }
    ]);
  });
  window.addEventListener('appinstalled', () => {
    const el = document.getElementById('wg-pwa-install');
    if (el) el.remove();
  });
}
